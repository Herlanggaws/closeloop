type GitLabConfig struct {
	BaseURL  string `json:"base_url"`
	Token    string `json:"token"`
	Username string `json:"username"`
}

func ParseGitLabConfig(raw json.RawMessage) (GitLabConfig, error) {
	if len(raw) == 0 {
		return GitLabConfig{}, fmt.Errorf("gitlab not configured")
	}
	var cfg GitLabConfig
	if err := json.Unmarshal(raw, &cfg); err != nil {
		return GitLabConfig{}, err
	}
	if cfg.Token == "" {
		var m map[string]any
		if err := json.Unmarshal(raw, &m); err == nil {
			if t, ok := m["api_token"].(string); ok {
				cfg.Token = t
			}
		}
	}
	if strings.TrimSpace(cfg.Token) == "" {
		return GitLabConfig{}, fmt.Errorf("gitlab token missing")
	}
	if strings.TrimSpace(cfg.BaseURL) == "" {
		cfg.BaseURL = "https://gitlab.com"
	}
	cfg.BaseURL = strings.TrimRight(cfg.BaseURL, "/")
	return cfg, nil
}

type AutoprExecutor interface {
	Execute(ctx context.Context, req AutoprExecRequest) (AutoprExecResult, error)
}

type AutoprExecRequest struct {
	Run               AutoprRun
	Ticket            Ticket
	GitHub            GitHubAppConfig
	GitLab            GitLabConfig
	RepoProvider      string
	RepoDefaultBranch string
	TicketURL         string
	CostCapCents      int
}

type AutoprExecResult struct {
	Branch    string
	PRURL     string
	PRNumber  int
	CostCents int
	Log       string
	// NeedsReroute stops the run without a PR: the fix belongs in SuggestedRepo (US-57).
	NeedsReroute  bool
	SuggestedRepo string
	Reason        string
}

type GitHubAutoprExecutor struct {
	Client *githubapp.Client
}

func (e *GitHubAutoprExecutor) Execute(ctx context.Context, req AutoprExecRequest) (AutoprExecResult, error) {
	ticketIDShort := req.Ticket.ID
	if len(ticketIDShort) > 8 {
		ticketIDShort = ticketIDShort[:8]
	}
	path := fmt.Sprintf(".saidloop/autopr-%s.md", ticketIDShort)
	content := fmt.Sprintf(`# Saidloop Auto PR

Ticket: %s
Type: %s
Status: %s

## Report

%s

## Notes

Generated by Saidloop Auto PR. This branch is for review only — Saidloop never merges.

Ticket URL: %s
`, req.Ticket.ID, req.Ticket.Type, req.Ticket.Status, req.Ticket.Title, req.TicketURL)

	cost := 25 // flat accounting until live model metering
	if req.CostCapCents > 0 && cost > req.CostCapCents {
		return AutoprExecResult{}, fmt.Errorf("cost cap exceeded")
	}

	if req.RepoProvider == "gitlab" {
		glClient, err := gitlab.New(gitlab.Config{
			BaseURL: req.GitLab.BaseURL,
			Token:   req.GitLab.Token,
		})
		if err != nil {
			return AutoprExecResult{Log: "failed to init gitlab client", CostCents: cost}, err
		}
		baseBranch := req.RepoDefaultBranch
		if baseBranch == "" {
			baseBranch = "main"
		}
		logLines := []string{
			"sandbox started",
			"limit: 15m · cost cap $2.00 · never merge",
			"cloning " + req.Run.Repo,
			"loading ticket context",
			"writing " + path,
			"opening GitLab merge request",
		}
		mr, err := glClient.CreateMergeRequest(ctx, gitlab.CreateMRInput{
			ProjectPath:   req.Run.Repo,
			BaseBranch:    baseBranch,
			HeadBranch:    fmt.Sprintf("saidloop/autopr-%s", ticketIDShort),
			CommitMessage: fmt.Sprintf("fix: address Saidloop ticket %s", ticketIDShort),
			MRTitle:       fmt.Sprintf("fix: %s", truncate(req.Ticket.Title, 72)),
			MRBody: fmt.Sprintf(`## Saidloop Auto PR

Fixes feedback ticket [%s](%s).

**Never merges automatically** — please review and merge manually.

---
_Generated by Saidloop_`, req.Ticket.ID, req.TicketURL),
			Files: []gitlab.FileChange{{Path: path, Content: content}},
		})
		if err != nil {
			return AutoprExecResult{Log: strings.Join(logLines, "\n"), CostCents: cost}, err
		}
		logLines = append(logLines, "GitLab MR opened: "+mr.WebURL)
		return AutoprExecResult{
			Branch:    mr.Branch,
			PRURL:     mr.WebURL,
			PRNumber:  mr.IID,
			CostCents: cost,
			Log:       strings.Join(logLines, "\n"),
		}, nil
	}

	if e == nil || e.Client == nil {
		return AutoprExecResult{}, fmt.Errorf("github app client not configured")
	}
	parts := strings.SplitN(req.GitHub.RepoFullName, "/", 2)
	if len(parts) != 2 {
		return AutoprExecResult{}, fmt.Errorf("invalid repo %q", req.GitHub.RepoFullName)
	}
	owner, repo := parts[0], parts[1]
	base := req.GitHub.DefaultBranch
	if base == "" {
		base = "main"
	}

	logLines := []string{
		"sandbox started",
		"limit: 15m · cost cap $2.00 · never merge",
		"cloning " + req.GitHub.RepoFullName,
		"loading ticket context",
		"writing " + path,
		"opening pull request",
	}

	pr, err := e.Client.CreatePullRequest(ctx, githubapp.CreatePRInput{
		InstallationID: req.GitHub.InstallationID,
		Owner:          owner,
		Repo:           repo,
		BaseBranch:     base,
		HeadBranch:     fmt.Sprintf("saidloop/autopr-%s", ticketIDShort),
		CommitMessage:  fmt.Sprintf("fix: address Saidloop ticket %s", ticketIDShort),
		PRTitle:        fmt.Sprintf("fix: %s", truncate(req.Ticket.Title, 72)),
		PRBody: fmt.Sprintf(`## Saidloop Auto PR

Fixes feedback ticket [%s](%s).

**Never merges automatically** — please review and merge manually.

---
_Generated by Saidloop_`, req.Ticket.ID, req.TicketURL),
		Files: []githubapp.FileChange{{Path: path, Content: content}},
	})
	if err != nil {
		return AutoprExecResult{Log: strings.Join(logLines, "\n"), CostCents: cost}, err
	}
	logLines = append(logLines, "PR opened: "+pr.HTMLURL)
	return AutoprExecResult{
		Branch:    pr.Branch,
		PRURL:     pr.HTMLURL,
		PRNumber:  pr.Number,
		CostCents: cost,
		Log:       strings.Join(logLines, "\n"),
	}, nil
}

func truncate(s string, n int) string {
	s = strings.TrimSpace(s)
	if len(s) <= n {
		return s
	}
	return s[:n-1] + "…"
}

func ProcessAutoprRun(ctx context.Context, store *Store, exec AutoprExecutor, webURL string, runID string) error {
	run, err := store.GetAutoprRun(ctx, runID)
	if err != nil {
		return err
	}
	if run.Status != "queued" && run.Status != "running" {
		return nil
	}

	now := time.Now().UTC()
	run.Status = "running"
	run.LogExcerpt = "starting…"
	_ = store.UpdateAutoprRun(ctx, run)

	ticket, err := store.GetTicket(ctx, run.TicketID)
	if err != nil {
		return failAutopr(ctx, store, run, err, true)
	}
	var ghCfg GitHubAppConfig
	var glCfg GitLabConfig
	repoProvider := "github"
	defaultBranch := "main"

	if repo, err := store.ProjectRepoByFullName(ctx, run.ProjectID, run.Repo); err == nil {
		if repo.Provider == "gitlab" {
			repoProvider = "gitlab"
		}
		if repo.DefaultBranch != "" {
			defaultBranch = repo.DefaultBranch
		}
		if repo.InstallationID != 0 {
			ghCfg.InstallationID = repo.InstallationID
		}
	}

	if repoProvider == "gitlab" {
		raw, err := store.GetIntegrationConfig(ctx, run.ProjectID, "gitlab")
		if err != nil {
			return failAutopr(ctx, store, run, err, true)
		}
		glCfg, err = ParseGitLabConfig(raw)
		if err != nil {
			return failAutopr(ctx, store, run, err, true)
		}
	} else {
		raw, err := store.GetIntegrationConfig(ctx, run.ProjectID, "github_app")
		if err != nil {
			return failAutopr(ctx, store, run, err, true)
		}
		ghCfg, err = ParseGitHubAppConfig(raw)
		if err != nil {
			return failAutopr(ctx, store, run, err, true)
		}
		// Write access covers the run's repo only (US-56, US-58).
		ghCfg.RepoFullName = run.Repo
		ghCfg.DefaultBranch = defaultBranch
	}

	ticketURL := strings.TrimRight(webURL, "/") + "/app/tickets/" + ticket.ID
	if exec == nil {
		return failAutopr(ctx, store, run, fmt.Errorf("autopr executor not configured"), true)
	}

	ctx, cancel := context.WithTimeout(ctx, 15*time.Minute)
	defer cancel()

	result, err := exec.Execute(ctx, AutoprExecRequest{
		Run:               run,
		Ticket:            ticket,
		GitHub:            ghCfg,
		GitLab:            glCfg,
		RepoProvider:      repoProvider,
		RepoDefaultBranch: defaultBranch,
		TicketURL:         ticketURL,
		CostCapCents:      AutoprCostCapCents,
	})
	run.LogExcerpt = result.Log
	run.CostCents = result.CostCents
	if err != nil {
		return failAutopr(ctx, store, run, err, true)
	}
	if result.NeedsReroute {
		return rerouteAutopr(ctx, store, run, result.SuggestedRepo, result.Reason)
	}

	finished := time.Now().UTC()
	run.Status = "succeeded"
	run.Branch = result.Branch
	run.PRURL = result.PRURL
	n := result.PRNumber
	run.PRNumber = &n
	run.FinishedAt = &finished
	run.Error = ""
	_ = now
	return store.UpdateAutoprRun(ctx, run)
}

// rerouteAutopr ends a run as needs_reroute: no PR, one credit refunded (US-57).
func rerouteAutopr(ctx context.Context, store *Store, run AutoprRun, suggested, reason string) error {
	finished := time.Now().UTC()
	run.Status = "needs_reroute"
	run.SuggestedRepo = strings.TrimSpace(suggested)
	run.RerouteReason = strings.TrimSpace(reason)
	run.PRURL = ""
	run.PRNumber = nil
	run.FinishedAt = &finished
	run.Error = ""
	if err := store.UpdateAutoprRun(ctx, run); err != nil {
		return err
	}
	return store.RefundAutoprCredit(ctx, run.OrgID, run.ID, "autopr_needs_reroute")
}

func failAutopr(ctx context.Context, store *Store, run AutoprRun, cause error, refund bool) error {
	finished := time.Now().UTC()
	run.Status = "failed"
	run.Error = cause.Error()
	run.FinishedAt = &finished
	_ = store.UpdateAutoprRun(ctx, run)
	if refund {
		_ = store.RefundAutoprCredit(ctx, run.OrgID, run.ID, "autopr_refund")
	}
	return cause
}
